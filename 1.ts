// Simple TypeScript Calculator

let num1: number = 30;
let num2: number = 5;

function add(a: number, b: number): number {
    return a + b;
}

function subtract(a: number, b: number): number {
    return a - b;
}

console.log("Addition:", add(num1, num2));
console.log("Subtraction:", subtract(num1, num2));